/** Noticias ordenadas de más reciente a más antigua */
export function getNewsSorted() {
  return [...news].sort((a, b) => b.dateISO.localeCompare(a.dateISO))
}

export function getLatestNews(limit = 3) {
  return getNewsSorted().slice(0, limit)
}

export function getNewsBySlug(slug: string) {
  return news.find((item) => item.slug === slug)
}

